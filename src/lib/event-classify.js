/**
 * 给活动判二级分类。
 * @returns {string} 二级名；一级类目未知时返回 ""
 */
export function classifySubcategory(event) {
  const category = event?.category;
  const rules = SUBCATEGORY_RULES[category];
  if (!rules) return "";

  const text = `${event?.title || ""} ${event?.summary || ""} ${event?.venue || ""}`;
  for (const [name, pattern] of rules) {
    if (pattern.test(text)) return name;
  }
  return SUBCATEGORY_FALLBACK[category] || "其他";
}

